const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { execFileSync } = require("node:child_process");
const test = require("node:test");
const { collectBuildInfo, writeBuildInfo } = require("../scripts/build-info.cjs");
const { getBuildInfo } = require("./build-info.cjs");
const vm = require("node:vm");

test("build identity captures commit, dirty source and actual feature policy without inventing a release", t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "archimedes-build-info-"));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  fs.mkdirSync(path.join(root, "src")); fs.mkdirSync(path.join(root, "shared"));
  fs.writeFileSync(path.join(root, "package.json"), JSON.stringify({ version: "0.1.0" }));
  fs.writeFileSync(path.join(root, "shared/research-apps.json"), JSON.stringify({ apps: { library: { defaultEnabled: true }, reproduce: { defaultEnabled: false, beta: true } } }));
  fs.writeFileSync(path.join(root, "src/cloud-features.ts"), "export const CLOUD_FEATURES_ENABLED = false;");
  const archiveSource = collectBuildInfo(root);
  assert.equal(archiveSource.commit, "unknown");
  assert.equal(archiveSource.sourceDirty, null);
  assert.equal(archiveSource.sourceFingerprint, null);
  assert.equal(archiveSource.channel, "unknown");
  const git = (...args) => execFileSync("git", args, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  git("init"); git("config", "user.email", "fixture@example.com"); git("config", "user.name", "Fixture");
  git("add", "."); git("commit", "-m", "fixture");
  const before = collectBuildInfo(root);
  assert.equal(before.commit, git("rev-parse", "HEAD"));
  assert.equal(before.sourceDirty, false);
  assert.equal(before.channel, "development");
  assert.equal(before.capabilities.cloudEntryPoints, false);
  assert.deepEqual(before.capabilities.defaultResearchApps, ["library"]);
  fs.writeFileSync(path.join(root, "src/cloud-features.ts"), "export const CLOUD_FEATURES_ENABLED = true;");
  const changed = writeBuildInfo(root, { channel: "preview" });
  assert.equal(changed.sourceDirty, true);
  assert.notEqual(changed.sourceFingerprint, before.sourceFingerprint);
  assert.equal(changed.capabilities.cloudEntryPoints, true);
  const packaged = getBuildInfo({ isPackaged: true, appPath: root, platform: "darwin", arch: "arm64" });
  assert.equal(packaged.channel, "preview");
  assert.equal(packaged.commit, before.commit);
  assert.equal(packaged.platform, "darwin"); assert.equal(packaged.arch, "arm64");
  assert.equal(packaged.packaged, true);
});

test("actual preload and main handler expose packaged identity and runtime target", async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "archimedes-build-bridge-"));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  fs.mkdirSync(path.join(root, ".archimedes"));
  fs.writeFileSync(path.join(root, ".archimedes/build-info.json"), JSON.stringify({ version: "0.1.0", commit: "fixture-commit", channel: "release", sourceDirty: false, sourceFingerprint: "fixture-source", capabilities: { cloudEntryPoints: false, defaultResearchApps: ["library"], betaResearchApps: [] } }));
  const main = fs.readFileSync(path.join(__dirname, "main.cjs"), "utf8");
  const start = main.indexOf('  ipcMain.handle("app:build-info",');
  const end = main.indexOf('  ipcMain.handle("window:initial-workspace",', start);
  assert.ok(start >= 0 && end > start, "reassess the actual handler boundaries");
  const handlers = new Map();
  vm.runInNewContext(main.slice(start, end), { ipcMain: { handle: (name, callback) => handlers.set(name, callback) }, app: { isPackaged: true, getAppPath: () => root }, process: { platform: "darwin", arch: "arm64" }, require: name => { assert.equal(name, "./build-info.cjs"); return { getBuildInfo }; } });
  let bridge;
  vm.runInNewContext(fs.readFileSync(path.join(__dirname, "preload.cjs"), "utf8"), { process: { platform: "darwin" }, require: name => { assert.equal(name, "electron"); return { contextBridge: { exposeInMainWorld: (_name, value) => { bridge = value; } }, ipcRenderer: { invoke: name => handlers.get(name)() }, webUtils: {} }; } });
  const result = await bridge.getBuildInfo();
  assert.equal(result.commit, "fixture-commit"); assert.equal(result.channel, "release");
  assert.equal(result.platform, "darwin"); assert.equal(result.arch, "arm64");
  assert.equal(result.capabilities.cloudEntryPoints, false);
});
